"""换参数核第二版结论：
C1 先分开再处理的打断次数 ≤ 全开的六成；C2 最长专注 ≥ 全开的 1.8 倍；C3 要紧的晚到或没看到 ≤ 全关的四成。"""
import copy, importlib.util
spec = importlib.util.spec_from_file_location('m', '按类别过一天.py'); m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
def var(**kw):
    p = copy.deepcopy(m.P)
    for k, v in kw.items():
        if '.' in k:
            cat, f = k.split('.'); p['cats'][cat][f] = v
        elif k == 'unlocks_分开': p['unlocks']['分开'] = v
        else: p[k] = v
    return p
cases = [('基准', {}),
 ('群一天 7 条（西班牙中位数）', {'群聊.n': 7}), ('群一天 60 条', {'群聊.n': 60}),
 ('私聊一天 10 条', {'私聊.n': 10}), ('私聊一天 36 条', {'私聊.n': 36}),
 ('营销、内容各 30 条', {'营销推送.n': 30, '内容推送.n': 30}), ('营销、内容各 3 条', {'营销推送.n': 3, '内容推送.n': 3}),
 ('群里要紧的多一倍（8%）', {'群聊.p_urgent': 0.08}), ('私聊要紧的少一半（4%）', {'私聊.p_urgent': 0.04}),
 ('要紧群只占四成', {'key_group_share': 0.4}), ('要紧群占九成', {'key_group_share': 0.9}),
 ('全关时群里碰巧看到 0.5', {'群聊.see': 0.5, '私聊.see': 0.8}), ('全关时群里碰巧看到 0.1', {'群聊.see': 0.1, '私聊.see': 0.4}),
 ('分开时解锁和全关一样（46 次）', {'unlocks_分开': 46.0}),
 ('缓 10 分钟', {'recover': 10.0}), ('缓 25 分钟', {'recover': 25.0}),
 ('极端：群 60、私聊 36、要紧群四成', {'群聊.n': 60, '私聊.n': 36, 'key_group_share': 0.4}),
 ('极端：群 7、营销内容各 3、分开解锁 46', {'群聊.n': 7, '营销推送.n': 3, '内容推送.n': 3, 'unlocks_分开': 46.0}),
]
print('| 情形 | 打断 开/关/分 | 最长专注 开/关/分（分钟） | 要紧的晚到或没看到 关/分（条/天） | C1 | C2 | C3 |')
print('|---|---|---|---|---|---|---|')
for name, kw in cases:
    r = m.summarize(var(**kw), days=800, seed=5); a, b, c = r['全开'], r['全关'], r['分开']
    lb = b['晚1小时以上'] + b['当天没看到']; lc = c['晚1小时以上'] + c['当天没看到']
    c1 = c['打断'] <= 0.6 * a['打断']; c2 = c['最长专注_分'] >= 1.8 * a['最长专注_分']; c3 = lc <= 0.4 * lb
    print(f"| {name} | {a['打断']:.0f}/{b['打断']:.0f}/{c['打断']:.0f} | {a['最长专注_分']:.0f}/{b['最长专注_分']:.0f}/{c['最长专注_分']:.0f} | {lb:.2f}/{lc:.2f} | {'✓' if c1 else '✗'} | {'✓' if c2 else '✗'} | {'✓' if c3 else '✗'} |")
