def md(n, d=0):
    t, k = n
    out = [f'# {t}'] if d == 0 else ['', f'## {t}'] if d == 1 else [f'### {t}'] if d == 2 else ['  ' * (d - 3) + f'- {t}']
    for c in k: out += md(c, d + 1)
    return out
def mm(n, d=0):
    t, k = n
    out = ['  ' * (d + 1) + t]
    for c in k: out += mm(c, d + 1)
    return out
def walk(n, d=0):
    yield d, n[0], len(n[1])
    for c in n[1]: yield from walk(c, d + 1)
