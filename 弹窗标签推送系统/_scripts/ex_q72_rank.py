names = list(PER1)
print('== 两两每 1% 倍数（行 ÷ 列），S / R')
allp = dict(PER1)
for k, v in POT.items():
    allp[k] = (v, v)
keys = list(allp)
for a in keys:
    row = []
    for b in keys:
        if a == b:
            continue
        s, r = allp[a][0] / allp[b][0], allp[a][1] / allp[b][1]
        tag = '同向>' if s > 1 and r > 1 else ('同向<' if s < 1 and r < 1 else '相反')
        row.append(f'{b}: {s:.2f}/{r:.2f} {tag}')
    print(a, '｜', '；'.join(row))

