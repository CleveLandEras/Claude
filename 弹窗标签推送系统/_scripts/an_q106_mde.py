"""设计卡 Q106 S3：首付率（二元）最小可检测幅度，只代公式、不读数据。
MDE（百分点）= 2.8 × √(p(1−p)(1/n1 + 1/n2)) × 100；双侧 5%、把握度 80%（与 A29 同）。
n：持續老账号 7,754、新注册 4,070（A19）；分组 50/50 与 20/80（20% 为对照）；p 为情景基线首付率（本地未知）。"""
import math
groups = {'持續老账号': 7754, '新注册': 4070}
ps = [0.01, 0.05, 0.50]
print('人群 | n | 分组 | p | MDE（百分点） | MDE 折合人数（× n ÷ 100）')
for name, n in groups.items():
    for split, (a, b) in {'50/50': (0.5, 0.5), '20/80': (0.2, 0.8)}.items():
        n1, n2 = n * a, n * b
        for p in ps:
            mde = 2.8 * math.sqrt(p * (1 - p) * (1 / n1 + 1 / n2)) * 100
            print(f'{name} | {n:,} | {split} | {p:.0%} | {mde:.2f} | 约 {mde * n / 100:,.0f} 人')
print('每 1 个百分点：持續老账号', f'{7754 / 100:.1f}', '人；新注册', f'{4070 / 100:.1f}', '人')
