def load(name):
    return open(os.path.join(BASE, name), encoding='utf-8').read()


def run(name, pairs):
    t = load(name)
    for i, (old, new) in enumerate(pairs, 1):
        n = t.count(old)
        if n != 1:
            print(f'[{name}] 第 {i} 条替换命中 {n} 次，终止：{old[:70]}')
            sys.exit(1)
        t = t.replace(old, new)
    shutil.copy(os.path.join(BASE, name), os.path.join(BK, name))
    open(os.path.join(BASE, name), 'w', encoding='utf-8').write(t)
    print(f'[{name}] 完成 {len(pairs)} 处')


