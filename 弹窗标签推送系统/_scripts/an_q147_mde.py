# 二元指标 MDE（绝对百分点）= (z_a + z_b) * sqrt(p(1-p)(1/n1 + 1/n2))；A29 方法 3 用系数 2.8（双侧 5%、把握度 80%）。
# 第 1 期末按判读规则 3 用 99% 区间：系数 = 2.576 + 0.842 = 3.418。
from math import sqrt

Z95 = 1.96 + 0.8416   # ≈ 2.80，与 A29 一致
Z99 = 2.5758 + 0.8416  # ≈ 3.417


def mde(n_total, share_treat, p, coef):
    n1 = n_total * share_treat
    n2 = n_total * (1 - share_treat)
    return coef * sqrt(p * (1 - p) * (1 / n1 + 1 / n2)) * 100  # 百分点


print("系数：95% 区间 =", round(Z95, 3), "；99% 区间 =", round(Z99, 3), "；99%/95% =", round(Z99 / Z95, 3))
print()

