"""R152：A31 S3 可检测幅度的人数换算，分「全体人数折算」与「试验处理组人数」两种口径（只代算术，不读数据）。
处理组 = 看到新内容的一组：50/50 为一半，20/80 为 80%。"""
rows = [('持續老账号', 7754, '50/50', 0.5, [0.63, 1.39, 3.18]),
        ('持續老账号', 7754, '20/80', 0.8, [0.79, 1.73, 3.97]),
        ('新注册', 4070, '50/50', 0.5, [0.87, 1.91, 4.39]),
        ('新注册', 4070, '20/80', 0.8, [1.09, 2.39, 5.49])]
for name, n, g, share, mdes in rows:
    t = n * share
    cells = []
    for m in mdes:
        cells.append(f'{m}：全体 {round(n*m/100)} / 处理组 {round(t*m/100)}')
    print(f'{name} n={n} {g} 处理组 {t:.1f} 人 | ' + ' | '.join(cells))
