import math
z95, z99 = 1.96 + 0.84, 2.576 + 0.84
k99 = z99 / z95
single = {"高卡去大户·分层": 8.7, "高卡去大户·不分层": 12.7, "在场付费者其余": 7.0, "高卡流失回来率(pp)": 9.2}
for k, v in single.items():
    print(f"{k}: 单期95% {v:.1f}｜第1期末99% {v*k99:.1f}｜合并3期95% {v/math.sqrt(3):.1f}–{v:.1f}")
for k in ["高卡去大户·分层", "在场付费者其余"]:
    v = single[k]
    print(f"{k}: 1% 所需人数倍数 单期 {v**2:.0f}｜合并3期 {(v/math.sqrt(3))**2:.0f}–{v**2:.0f}")
