# 只读：护栏「每期都看、任一突破即不过」在真实效果为 0 时的误判「不过」概率（独立近似上界）
# 突破定义：处理组朝坏方向变且 95% 区间不含 0 => 单侧 2.5%
from statistics import NormalDist

a1 = 0.025
for k in (3, 4, 5, 7):
    one = 1 - (1 - a1) ** k
    three = 1 - (1 - a1) ** (3 * k)
    print(f"护栏 {k} 项：单期误判不过 {one:.1%}；看满 3 期（独立上界） {three:.1%}")

# 对照：若护栏也只在两个时点、用 99% 区间（单侧 0.5%）
a2 = 0.005
for k in (3, 4, 5, 7):
    two = 1 - (1 - a2) ** (2 * k)
    print(f"护栏 {k} 项，两个时点 99%：{two:.1%}")

# 主指标两时点（99% 后 95%）单侧误判「过」的上界
print("主指标误判『过』上界（两时点）：", f"{1-(1-0.005)*(1-0.025):.1%}")
print("z 0.975 =", round(NormalDist().inv_cdf(0.975), 3), " z 0.995 =", round(NormalDist().inv_cdf(0.995), 3))
