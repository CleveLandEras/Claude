def cut(a, b, new, text):
    i, j = text.index(a), text.index(b)
    assert i < j
    return text[:i] + new + text[j:]


def rep(old, new, text):
    assert text.count(old) == 1, (text.count(old), old[:50])
    return text.replace(old, new)


