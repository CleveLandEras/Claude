from math import sqrt

print("== Q106 MDE（二元，2.8 × sqrt(p(1-p)(1/n1+1/n2))）==")
for n in (7754, 4070):
    for share in (0.5, 0.2):
        n1 = n * share
        n2 = n - n1
        row = []
        for p in (0.01, 0.05, 0.5):
            mde = 2.8 * sqrt(p * (1 - p) * (1 / n1 + 1 / n2))
            row.append(f"p={p:.2f}: {mde*100:.2f}pp 全体折算{mde*n:.0f}人 处理组折算{mde*n2:.0f}人")
        print(n, f"对照{share:.0%}", " | ".join(row))
print("每1个百分点：", 7754 * 0.01, 4070 * 0.01)

