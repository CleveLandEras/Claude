def cell(ws, r, c, v, font=F, fill=None, border=True):
    x = ws.cell(row=r, column=c, value=v)
    x.font = font
    x.alignment = WRAP
    if fill:
        x.fill = fill
    if border:
        x.border = BD
    return x


