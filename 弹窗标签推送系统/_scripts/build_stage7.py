def tag(k, t):
    return f'<span class="tag {k}">{t}</span>'

RES = {'可实现': 't-goal', '依赖推断': 't-inf', '部分实现': 't-sug', '不可实现': 't-con'}
def res(t):
    return tag(RES[t], t)

def src(t):
    return f'<span class="src">{t}</span>'

def table(head, rows, widths=None):
    h = ''.join(f'<th>{x}</th>' for x in head)
    out = f'<div class="tw"><table>\n<tr>{h}</tr>\n'
    for r in rows:
        if isinstance(r, str):
            out += f'<tr class="grp"><td colspan="{len(head)}">{r}</td></tr>\n'
        else:
            out += '<tr>' + ''.join(f'<td class="no">{c}</td>' if (i == 0 and head[0] in ('场景', '序')) else f'<td>{c}</td>' for i, c in enumerate(r)) + '</tr>\n'
    out += '</table></div>\n'
    return out

def sec(no, sid, h2, sub, body):
    s = f'<section class="sec" id="{sid}"><div class="sec-h"><span class="sec-no">{no}</span><h2>{h2}</h2></div>\n'
    if sub:
        s += f'<p class="sec-sub">{sub}</p>\n'
    return s + body + '</section>\n'

def h3(t):
    return f'<h3 style="margin:14px 0 6px;font-size:15px">{t}</h3>\n'

def note(t):
    return f'<p class="note">{t}</p>\n'

