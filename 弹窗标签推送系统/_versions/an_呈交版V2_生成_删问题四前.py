def bars(s, x, y, rows, track=3.0, lw=1.25, rowh=0.44):
    """rows: (label, sub, solid_pct, range_pct, value, vsub, color)"""
    for i, (lab, sub, a, b, val, vsub, col) in enumerate(rows):
        yy = y + i * rowh
        text(s, x, yy, lw, 0.3, lab, size=12, color=INK, line=1.0)
        rect(s, x + lw, yy + 0.05, track, 0.14, 'EAE7E0')
        if a:
            rect(s, x + lw, yy + 0.05, track * a / 100, 0.14, col)
        if b:
            rect(s, x + lw + track * a / 100, yy + 0.05, track * (b - a) / 100, 0.14, BAR_G)
        text(s, x + lw + track + 0.15, yy - 0.02, 2.75, 0.3, [[(val, {'bold': True, 'color': RED if col == RED else NAVY}), ('　' + vsub, {'size': 10.5, 'color': MUTE})]], size=12.5, line=1.0)


